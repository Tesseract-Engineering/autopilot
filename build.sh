#!/usr/bin/env bash
# Generate adapters from core/. Adapters are never hand-edited.
#   ./build.sh          regenerate plugins/autopilot/
#   ./build.sh --check  fail (exit 1) if plugins/autopilot/ is out of date
set -euo pipefail
shopt -s nullglob
ROOT="$(cd "$(dirname "$0")" && pwd)"
OUT="$ROOT/plugins/autopilot"

generate() { # $1 = output dir
  local out="$1"
  rm -rf "${out:?}"
  mkdir -p "$out/.claude-plugin" "$out/hooks" "$out/scripts/claude" "$out/agents" "$out/skills"

  cp "$ROOT/adapters/claude/plugin.json" "$out/.claude-plugin/plugin.json"
  cp "$ROOT/adapters/claude/hooks.json" "$out/hooks/hooks.json"

  # Core scripts are copied in: an installed plugin is cached on its own and
  # can't reach ../../core at runtime.
  cp -R "$ROOT/core/scripts/." "$out/scripts/"
  cp -R "$ROOT/adapters/claude/shims/." "$out/scripts/claude/"
  cp -R "$ROOT/core/skills/." "$out/skills/"

  # Agents = Claude frontmatter (adapter) + role prompt (core, metadata stripped).
  local role name
  for role in "$ROOT"/core/roles/*.md; do
    name="$(basename "$role" .md)"
    [ -f "$ROOT/adapters/claude/agents/$name.yml" ] || { echo "missing adapters/claude/agents/$name.yml" >&2; exit 1; }
    {
      echo "---"
      cat "$ROOT/adapters/claude/agents/$name.yml"
      echo "---"
      echo "<!-- GENERATED by build.sh from core/roles/$name.md. Do not edit. -->"
      awk 'NR==1 && /^---$/ {fm=1; next} fm && /^---$/ {fm=0; next} !fm' "$role"
    } > "$out/agents/$name.md"
  done
  find "$out/scripts" -name '*.sh' -exec chmod +x {} +
}

if [ "${1:-}" = "--check" ]; then
  tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
  generate "$tmp/autopilot"
  if diff -r "$tmp/autopilot" "$OUT" >/dev/null; then
    echo "build --check: plugins/autopilot is up to date"
  else
    echo "build --check: plugins/autopilot is stale; run ./build.sh" >&2
    diff -r "$tmp/autopilot" "$OUT" >&2 || true
    exit 1
  fi
else
  generate "$OUT"
  echo "generated $OUT"
fi
